    [SpacetimeDB.Reducer(ReducerKind.Init)]
    public static void Init(ReducerContext ctx)
    {
        ctx.Db.WorldState.Insert(new WorldStateRow
        {
            WorldId      = DefaultWorldId,
            Tick         = 0,
            Cycle        = 0,
            RngState     = ctx.Timestamp.MicrosecondsSinceUnixEpoch,
            ForestTotal  = 0,
            CarbonTotal  = 0,
            InitialForest = 0,
            CarbonCap    = 1000,
            RecoveryIndexBuilt = false
        });

        // Schedule the cycle clock to fire every 30 seconds, repeating
        ctx.Db.CycleClock.Insert(new CycleClockRow
        {
            Id          = 0,
            ScheduledAt = new ScheduleAt.Interval(TimeSpan.FromSeconds(30))
        });

        string seedUsernameNormalized = NormalizeCredentialUsername(SeedCredentialUsername);
        if (ctx.Db.CredentialAccounts.UsernameNormalized.Find(seedUsernameNormalized) is not CredentialAccountRow)
        {
            long seedNowMs = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
            string seedWallet = BuildCredentialWalletAddress(seedUsernameNormalized);
            string seedSalt = BuildPasswordSalt(seedUsernameNormalized, seedNowMs);
            string seedHash = HashCredentialPassword(SeedCredentialPassword, seedSalt);

            ctx.Db.CredentialAccounts.Insert(new CredentialAccountRow
            {
                UsernameNormalized = seedUsernameNormalized,
                Wallet = seedWallet,
                Username = SeedCredentialUsername,
                DisplayName = SeedCredentialUsername,
                PasswordSalt = seedSalt,
                PasswordHash = seedHash,
                CreatedAtMs = seedNowMs,
                UpdatedAtMs = seedNowMs
            });

            ctx.Db.PlayerIdentities.Insert(new PlayerIdentityRow
            {
                Wallet = seedWallet,
                UsernameNormalized = seedUsernameNormalized,
                Username = SeedCredentialUsername,
                DisplayName = SeedCredentialUsername,
                CreatedAtMs = seedNowMs,
                UpdatedAtMs = seedNowMs
            });
        }

        Log.Info("Finite Earth module initialized.");
    }

