    private static long NextRngState(long state, long tick)
    {
        long normalized = NormalizeNonNegative(state);
        if (normalized > RngWrapThreshold)
            normalized %= RngWrapBase;

        long tickMix = PositiveMod(tick, 1_000L) * RngTickMix;
        return normalized + RngStep + tickMix;
    }

    private static long NormalizeNonNegative(long value)
    {
        if (value >= 0)
            return value;
        if (value == long.MinValue)
            return long.MaxValue;
        return -value;
    }

    private static long PositiveMod(long value, long modulus)
    {
        long result = value % modulus;
        return result < 0 ? result + modulus : result;
    }

