    [SpacetimeDB.Procedure]
    public static CredentialAuthResult CredentialLogin(ProcedureContext ctx, string username, string password)
    {
        long seedNowMs = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
        return ctx.WithTx(txCtx =>
        {
            if (txCtx.Db.CredentialAccounts.UsernameNormalized.Find(NormalizeCredentialUsername(SeedCredentialUsername)) is not CredentialAccountRow)
            {
                string seedUsernameNormalized = NormalizeCredentialUsername(SeedCredentialUsername);
                string seedWallet = BuildCredentialWalletAddress(seedUsernameNormalized);
                string seedSalt = BuildPasswordSalt(seedUsernameNormalized, seedNowMs);
                string seedHash = HashCredentialPassword(SeedCredentialPassword, seedSalt);

                txCtx.Db.CredentialAccounts.Insert(new CredentialAccountRow
                {
                    UsernameNormalized = seedUsernameNormalized,
                    Wallet = seedWallet,
                    Username = SeedCredentialUsername,
                    DisplayName = SeedCredentialUsername,
                    PasswordSalt = seedSalt,
                    PasswordHash = seedHash,
                    CreatedAtMs = seedNowMs,
                    UpdatedAtMs = seedNowMs
                });

                txCtx.Db.PlayerIdentities.Insert(new PlayerIdentityRow
                {
                    Wallet = seedWallet,
                    UsernameNormalized = seedUsernameNormalized,
                    Username = SeedCredentialUsername,
                    DisplayName = SeedCredentialUsername,
                    CreatedAtMs = seedNowMs,
                    UpdatedAtMs = seedNowMs
                });
            }

            string normalizedUsername = NormalizeCredentialUsername(username);
            if (!IsValidCredentialUsername(username))
            {
                return RejectCredentialAuth("Invalid username or password.");
            }

            if (string.IsNullOrEmpty(password))
            {
                return RejectCredentialAuth("Invalid username or password.");
            }

            if (txCtx.Db.CredentialAccounts.UsernameNormalized.Find(normalizedUsername) is not CredentialAccountRow account)
            {
                return RejectCredentialAuth("Invalid username or password.");
            }

            if (!VerifyCredentialPassword(password, account.PasswordSalt, account.PasswordHash))
            {
                return RejectCredentialAuth("Invalid username or password.");
            }

            if (txCtx.Db.PlayerIdentities.Wallet.Find(account.Wallet) is PlayerIdentityRow identity)
            {
                txCtx.Db.PlayerIdentities.Wallet.Update(identity with
                {
                    UsernameNormalized = account.UsernameNormalized,
                    Username = account.Username,
                    DisplayName = account.DisplayName,
                    UpdatedAtMs = account.UpdatedAtMs
                });
            }
            else
            {
                txCtx.Db.PlayerIdentities.Insert(new PlayerIdentityRow
                {
                    Wallet = account.Wallet,
                    UsernameNormalized = account.UsernameNormalized,
                    Username = account.Username,
                    DisplayName = account.DisplayName,
                    CreatedAtMs = account.CreatedAtMs,
                    UpdatedAtMs = account.UpdatedAtMs
                });
            }

            return AcceptCredentialAuth(account.Wallet, account.Username, account.DisplayName, false);
        });
    }

