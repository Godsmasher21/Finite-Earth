    private static ulong StableWalletHash(string wallet)
    {
        if (string.IsNullOrEmpty(wallet))
            return 0UL;

        ulong hash = 1469598103934665603UL;
        for (int i = 0; i < wallet.Length; i++)
        {
            hash ^= wallet[i];
            hash *= 1099511628211UL;
        }

        return hash;
    }

