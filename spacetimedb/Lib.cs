    private static bool HasActivePactBetween(ReducerContext ctx, string walletA, string walletB, int pactType)
    {
        if (string.IsNullOrWhiteSpace(walletA) || string.IsNullOrWhiteSpace(walletB))
            return false;

        foreach (var pact in ctx.Db.Pacts.Iter())
        {
            if (pact.Status != 1 || pact.Type != pactType)
                continue;

            bool matchesForward = pact.WalletA == walletA && pact.WalletB == walletB;
            bool matchesReverse = pact.WalletA == walletB && pact.WalletB == walletA;
            if (matchesForward || matchesReverse)
                return true;
        }

        return false;
    }

    private static bool IsClaimBlockedByNonAggressionPact(ReducerContext ctx, int q, int r, string claimantWallet)
    {
        bool even = (r & 1) == 0;
        int[] dqs = even ? new[] { +1,  0, -1, -1, -1,  0 }
                         : new[] { +1, +1,  0, -1,  0, +1 };
        int[] drs  = new[] { 0, +1, +1,  0, -1, -1 };

        for (int i = 0; i < 6; i++)
        {
            long neighborId = PackTileId(q + dqs[i], r + drs[i]);
            if (ctx.Db.Tiles.Id.Find(neighborId) is not TileRow neighbor)
                continue;

            if (string.IsNullOrWhiteSpace(neighbor.Owner) || neighbor.Owner == claimantWallet)
                continue;

            if (HasActivePactBetween(ctx, claimantWallet, neighbor.Owner, 0))
                return true;
        }

        return false;
    }

    private static string ComputeReputation(PlayerRow p)
    {
        int total = p.EcoActions + p.IndustrialActions + p.AgricultureActions;
        if (total == 0) return "Balanced";
        float eco = (float)p.EcoActions / total;
        float ind = (float)p.IndustrialActions / total;
        float agr = (float)p.AgricultureActions / total;
        if (eco >= 0.6f) return "Conservationist";
        if (ind >= 0.6f) return "Industrialist";
        if (agr >= eco && agr >= ind) return "Agriculturist";
        return "Balanced";
    }

