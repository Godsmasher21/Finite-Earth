    // Offset-coordinate (even-row) hex distance using cube-coordinate conversion.
    // Matches Unity's EvenRowNeighbors / OddRowNeighbors tables.
    private static int OffsetHexDist(int q1, int r1, int q2, int r2)
    {
        int x1 = q1 - (r1 - (r1 & 1)) / 2;
        int z1 = r1;
        int y1 = -x1 - z1;
        int x2 = q2 - (r2 - (r2 & 1)) / 2;
        int z2 = r2;
        int y2 = -x2 - z2;
        return Math.Max(Math.Abs(x1 - x2), Math.Max(Math.Abs(y1 - y2), Math.Abs(z1 - z2)));
    }

    private static bool IsAdjacentToOwned(ReducerContext ctx, int q, int r, string wallet)
    {
        // Even-row offset neighbors match Unity's EvenRowNeighbors / OddRowNeighbors
        bool even = (r & 1) == 0;
        int[] dqs = even ? new[] { +1,  0, -1, -1, -1,  0 }
                         : new[] { +1, +1,  0, -1,  0, +1 };
        int[] drs  = new[] { 0, +1, +1,  0, -1, -1 };
        for (int i = 0; i < 6; i++)
            if (IsOwnedTile(ctx, q + dqs[i], r + drs[i], wallet)) return true;
        return false;
    }

    private static bool IsAdjacentToTerrain(ReducerContext ctx, int q, int r, int terrain)
    {
        bool even = (r & 1) == 0;
        int[] dqs = even ? new[] { +1,  0, -1, -1, -1,  0 }
                         : new[] { +1, +1,  0, -1,  0, +1 };
        int[] drs  = new[] { 0, +1, +1,  0, -1, -1 };
        for (int i = 0; i < 6; i++)
        {
            long neighborId = PackTileId(q + dqs[i], r + drs[i]);
            if (ctx.Db.Tiles.Id.Find(neighborId) is TileRow neighbor && neighbor.Terrain == terrain)
                return true;
        }
        return false;
    }

    private static bool IsHexAdjacent(int q1, int r1, int q2, int r2)
    {
        return OffsetHexDist(q1, r1, q2, r2) == 1;
    }

    private static bool HasTerrainWithinRadius(ReducerContext ctx, int q, int r, int terrain, int radius)
    {
        for (int candidateR = r - radius; candidateR <= r + radius; candidateR++)
