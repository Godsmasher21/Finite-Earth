    private static bool IsValidCredentialUsername(string username)
    {
        if (string.IsNullOrWhiteSpace(username))
            return false;

        string trimmed = username.Trim();
        if (trimmed.Length < CredentialUsernameMinLength || trimmed.Length > CredentialUsernameMaxLength)
            return false;

        foreach (char c in trimmed)
        {
            if (!(char.IsLetterOrDigit(c) || c == '_'))
                return false;
        }

        return true;
    }

