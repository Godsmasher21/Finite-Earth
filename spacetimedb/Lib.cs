    [SpacetimeDB.Reducer]
    public static void ArmySpawn(ReducerContext ctx, string owner, int q, int r)
    {
        long tileId = PackTileId(q, r);
        if (ctx.Db.Tiles.Id.Find(tileId) is not TileRow tile || tile.Owner != owner || tile.Building != B_BARRACKS)
        {
            Log.Warn($"ArmySpawn: {owner} needs barracks at ({q},{r}).");
            return;
        }

        if (ctx.Db.Players.Wallet.Find(owner) is not PlayerRow p) return;
        if (p.Wood < 2 || p.Food < 5) { Log.Warn($"ArmySpawn: {owner} cannot afford."); return; }

        ctx.Db.Players.Wallet.Update(p with { Wood = p.Wood - 2, Food = p.Food - 5 });

        long tick = ctx.Db.WorldState.WorldId.Find(DefaultWorldId) is WorldStateRow ws ? ws.Tick : 0;
        ctx.Db.Armies.Insert(new ArmyRow { Id = 0, Owner = owner, Q = q, R = r, LastMoveTick = tick });
    }

    [SpacetimeDB.Reducer]
    public static void ArmyMove(ReducerContext ctx, ulong armyId, string owner, int q, int r)
    {
        if (ctx.Db.Armies.Id.Find(armyId) is not ArmyRow army || army.Owner != owner) return;

        long tick = ctx.Db.WorldState.WorldId.Find(DefaultWorldId) is WorldStateRow ws ? ws.Tick : 0;
        if (tick - army.LastMoveTick < 1) { Log.Warn("ArmyMove: rate limited."); return; }

        if (!IsHexAdjacent(army.Q, army.R, q, r)) { Log.Warn("ArmyMove: not adjacent."); return; }

        if (ctx.Db.Tiles.Id.Find(PackTileId(q, r)) is TileRow dest && dest.Terrain == T_WATER)
        { Log.Warn("ArmyMove: cannot enter water."); return; }

        // Combat: if a rival army occupies the target tile, both are destroyed (draw).
        // If the target army is friendly, block the move instead.
        ArmyRow? occupant = null;
        foreach (var a in ctx.Db.Armies.Iter())
        {
            if (a.Q == q && a.R == r && a.Id != armyId) { occupant = a; break; }
        }
        if (occupant != null)
        {
            if (occupant.Value.Owner == owner)
            { Log.Warn("ArmyMove: tile occupied by friendly army."); return; }
            // Rival — mutual destruction.
            ctx.Db.Armies.Id.Delete(occupant.Value.Id);
            ctx.Db.Armies.Id.Delete(armyId);
            return;
        }

        ctx.Db.Armies.Id.Update(army with { Q = q, R = r, LastMoveTick = tick });
    }

