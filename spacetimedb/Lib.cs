    // Pure-C# 256-bit hash (4 × 64-bit FNV-1a lanes with avalanche finalization).
    // Replaces System.Security.Cryptography.SHA256 which causes a WASM stack overflow
    // in the SpacetimeDB runtime due to recursive managed-crypto initialization.
    private static string ComputeSha256Hex(string value)
    {
        byte[] data = Encoding.UTF8.GetBytes(value ?? string.Empty);
        return PureHash256(data);
    }

    private static string PureHash256(byte[] data)
    {
        unchecked
        {
            ulong h0 = 14695981039346656037UL;
            ulong h1 = 14695981039346656037UL ^ 0xdeadbeef12345678UL;
            ulong h2 = 14695981039346656037UL ^ 0x0123456789abcdefUL;
            ulong h3 = 14695981039346656037UL ^ 0xfedcba9876543210UL;

            for (int i = 0; i < data.Length; i++)
            {
                ulong b = data[i];
                h0 = (h0 ^ b) * 1099511628211UL;
                h1 = (h1 ^ (b + 1UL)) * 1099511628211UL;
                h2 = (h2 ^ (b + 2UL)) * 1099511628211UL;
                h3 = (h3 ^ (b + 3UL)) * 1099511628211UL;
                h0 ^= h1 >> 33;
                h1 ^= h2 >> 29;
                h2 ^= h3 >> 31;
                h3 ^= h0 >> 17;
            }

            // Finalization — 4 rounds of xorshift-multiply avalanche
            for (int r = 0; r < 4; r++)
            {
                h0 ^= h0 >> 33; h0 *= 0xff51afd7ed558ccdUL; h0 ^= h0 >> 33;
                h1 ^= h1 >> 29; h1 *= 0xc4ceb9fe1a85ec53UL; h1 ^= h1 >> 29;
                h2 ^= h2 >> 31; h2 *= 0x87c37b91114253d5UL; h2 ^= h2 >> 31;
                h3 ^= h3 >> 17; h3 *= 0x4cf5ad432745937fUL; h3 ^= h3 >> 17;
                h0 ^= h1 + h2; h1 ^= h2 + h3; h2 ^= h3 + h0; h3 ^= h0 + h1;
            }

            return $"{h0:x16}{h1:x16}{h2:x16}{h3:x16}";
        }
    }

