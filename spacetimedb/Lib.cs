    private static bool NeedsDerivedStateBackfill(PlayerRow player)
    {
        return player.OwnedTiles > 0
            && player.SettlementCount == 0
            && player.IndustryCount == 0
            && player.RecoveryProjectCount == 0
            && player.ForestTiles == 0
            && player.FarmlandTiles == 0;
    }

    private static PlayerRow RebuildPlayerDerivedState(ReducerContext ctx, PlayerRow player)
    {
        OwnedTileStats stats = default;
        foreach (var tile in ctx.Db.Tiles.Iter())
        {
            if (!string.Equals(tile.Owner, player.Wallet, StringComparison.Ordinal))
                continue;

            AccumulateOwnedTileStats(ref stats, tile);
        }

        return player with
        {
            OwnedTiles = stats.OwnedTiles,
            ForestTiles = stats.ForestTiles,
            FarmlandTiles = stats.FarmlandTiles,
            SettlementCount = stats.SettlementCount,
            IndustryCount = stats.IndustryCount,
            RecoveryProjectCount = stats.RecoveryProjectCount
        };
    }

    private static void ApplyOwnedTileStatsDelta(ref PlayerRow player, TileRow beforeTile, TileRow afterTile)
    {
        OwnedTileStats before = default;
        OwnedTileStats after = default;
        if (string.Equals(beforeTile.Owner, player.Wallet, StringComparison.Ordinal))
            AccumulateOwnedTileStats(ref before, beforeTile);
        if (string.Equals(afterTile.Owner, player.Wallet, StringComparison.Ordinal))
            AccumulateOwnedTileStats(ref after, afterTile);

        ApplyOwnedTileStatsDelta(ref player, after.OwnedTiles - before.OwnedTiles,
            after.ForestTiles - before.ForestTiles,
            after.FarmlandTiles - before.FarmlandTiles,
            after.SettlementCount - before.SettlementCount,
            after.IndustryCount - before.IndustryCount,
            after.RecoveryProjectCount - before.RecoveryProjectCount);
    }

    private static void ApplyOwnedTileStatsDelta(
        ref PlayerRow player,
        int ownedTilesDelta,
        int forestTilesDelta,
        int farmlandTilesDelta,
        int settlementCountDelta,
        int industryCountDelta,
        int recoveryProjectCountDelta)
    {
        player = player with
        {
            OwnedTiles = Math.Max(0, player.OwnedTiles + ownedTilesDelta),
            ForestTiles = Math.Max(0, player.ForestTiles + forestTilesDelta),
            FarmlandTiles = Math.Max(0, player.FarmlandTiles + farmlandTilesDelta),
            SettlementCount = Math.Max(0, player.SettlementCount + settlementCountDelta),
            IndustryCount = Math.Max(0, player.IndustryCount + industryCountDelta),
            RecoveryProjectCount = Math.Max(0, player.RecoveryProjectCount + recoveryProjectCountDelta)
        };
    }

    private static void AccumulateOwnedTileStats(ref OwnedTileStats stats, TileRow tile)
    {
        stats.OwnedTiles++;
        if (tile.Terrain == T_FOREST)
            stats.ForestTiles++;
        else if (tile.Terrain == T_FARMLAND)
            stats.FarmlandTiles++;

        switch (tile.Building)
        {
            case B_SETTLEMENT:
                stats.SettlementCount++;
                break;
            case B_INDUSTRY:
                stats.IndustryCount++;
                break;
            case B_RECOVERY:
                stats.RecoveryProjectCount++;
                break;
        }
    }

    private static PlayerRow LoadPlayerForIntent(ReducerContext ctx, string wallet)
    {
        if (ctx.Db.Players.Wallet.Find(wallet) is PlayerRow existing)
        {
            if (!NeedsDerivedStateBackfill(existing))
                return existing;

            PlayerRow rebuilt = RebuildPlayerDerivedState(ctx, existing);
            if (!rebuilt.Equals(existing))
                ctx.Db.Players.Wallet.Update(rebuilt);
            return rebuilt;
        }

        return EnsurePlayerRow(ctx, wallet);
    }

    private static PlayerRow EnsurePlayerRow(ReducerContext ctx, string wallet)
    {
        if (ctx.Db.Players.Wallet.Find(wallet) is PlayerRow existing)
        {
            if (existing.OwnedTiles >= StarterBootstrapOwnedTileLimit && !NeedsDerivedStateBackfill(existing))
                return existing;

            var current = existing;
            if (current.OwnedTiles <= 0)
            {
                current = BootstrapPlayerTerritory(ctx, current);
            }
            else if (current.OwnedTiles < StarterBootstrapOwnedTileLimit)
            {
                EnsureOwnedStarterBuildZone(ctx, current.Wallet);
                current = RebuildPlayerDerivedState(ctx, current);
            }

            if (NeedsDerivedStateBackfill(current))
            {
                current = RebuildPlayerDerivedState(ctx, current);
            }

            if (!current.Equals(existing))
            {
                ctx.Db.Players.Wallet.Update(current);
            }

            return current;
        }

        var created = CreatePlayerRow(wallet);
        created = BootstrapPlayerTerritory(ctx, created);
        ctx.Db.Players.Insert(created);
        return created;
    }

    private static PlayerRow BootstrapPlayerTerritory(ReducerContext ctx, PlayerRow player)
    {
        PlayerRow current = RebuildPlayerDerivedState(ctx, player);
        if (current.OwnedTiles > 0)
            return current;

        if (!TryFindStarterTile(ctx, player.Wallet, out TileRow starter))
            return current;

        long tick = ctx.Db.WorldState.WorldId.Find(DefaultWorldId) is WorldStateRow ws ? ws.Tick : 0L;
        TileRow claimedStarter = starter with
        {
            Terrain = T_PLAINS,
            Building = B_SETTLEMENT,
            Owner = player.Wallet,
            MiningCount = 0,
            LastUpdate = tick
        };

        ctx.Db.Tiles.Id.Update(claimedStarter);
        UpsertRecoveryCandidate(ctx, claimedStarter);
        ClaimSettlementRadius(ctx, player.Wallet, claimedStarter.Q, claimedStarter.R, tick);
        EnsureStarterBuildZone(ctx, player.Wallet, claimedStarter.Q, claimedStarter.R, tick);
        current = RebuildPlayerDerivedState(ctx, current with { Wallet = player.Wallet });
        Log.Info($"Bootstrapped starter territory for {player.Wallet} at ({claimedStarter.Q},{claimedStarter.R}) with {current.OwnedTiles} owned tiles.");
        return current;
    }

    private static bool TryFindStarterTile(ReducerContext ctx, string wallet, out TileRow starter)
    {
        var configuredPreferred = CollectConfiguredStarterTiles(ctx, preferProductiveLand: true);
        var configuredFallback = CollectConfiguredStarterTiles(ctx, preferProductiveLand: false);
        var preferred = new List<TileRow>();
        var fallback = new List<TileRow>();
        List<(int q, int r)> occupiedSettlements = CollectOccupiedSettlementOrigins(ctx);

        if (TrySelectStarterTile(FilterStarterCandidates(configuredPreferred, occupiedSettlements), wallet, out starter))
            return true;

        if (TrySelectStarterTile(configuredPreferred, wallet, out starter))
            return true;

        if (TrySelectStarterTile(FilterStarterCandidates(configuredFallback, occupiedSettlements), wallet, out starter))
            return true;

        if (TrySelectStarterTile(configuredFallback, wallet, out starter))
            return true;

        foreach (var tile in ctx.Db.Tiles.Iter())
        {
            if (!string.IsNullOrWhiteSpace(tile.Owner) || tile.Building != B_NONE)
                continue;

            if (tile.Terrain == T_PLAINS)
            {
                preferred.Add(tile);
            }
            else if (tile.Terrain != T_WATER && tile.Terrain != T_ICE)
            {
                fallback.Add(tile);
            }
        }

        if (TrySelectStarterTile(FilterStarterCandidates(preferred, occupiedSettlements), wallet, out starter))
            return true;

        if (TrySelectStarterTile(preferred, wallet, out starter))
            return true;

        if (TrySelectStarterTile(FilterStarterCandidates(fallback, occupiedSettlements), wallet, out starter))
            return true;

        return TrySelectStarterTile(fallback, wallet, out starter);
    }

    private static List<TileRow> CollectConfiguredStarterTiles(ReducerContext ctx, bool preferProductiveLand)
    {
        var starters = new List<TileRow>(DefaultStarterSpawnPoints.Length);

        for (int i = 0; i < DefaultStarterSpawnPoints.Length; i++)
        {
            (int q, int r) spawn = DefaultStarterSpawnPoints[i];
            if (ctx.Db.Tiles.Id.Find(PackTileId(spawn.q, spawn.r)) is not TileRow tile)
                continue;

            if (!string.IsNullOrWhiteSpace(tile.Owner) || tile.Building != B_NONE)
                continue;

            if (tile.Terrain == T_WATER || tile.Terrain == T_ICE)
                continue;

            if (preferProductiveLand && tile.Terrain != T_PLAINS && tile.Terrain != T_FOREST)
                continue;

            starters.Add(tile);
        }

        return starters;
    }

    private static void EnsureStarterBuildZone(ReducerContext ctx, string wallet, int originQ, int originR, long tick)
    {
        int plainsCount = 0;
        var candidates = new List<TileRow>();

        for (int r = originR - SettlementRadius; r <= originR + SettlementRadius; r++)
        {
            for (int q = originQ - SettlementRadius; q <= originQ + SettlementRadius; q++)
            {
                if (OffsetHexDist(q, r, originQ, originR) > SettlementRadius)
                    continue;

                if (ctx.Db.Tiles.Id.Find(PackTileId(q, r)) is not TileRow tile)
                    continue;

                if (!string.Equals(tile.Owner, wallet, StringComparison.Ordinal))
                    continue;

                if (tile.Terrain == T_PLAINS)
                {
                    plainsCount++;
                    continue;
                }

                if (tile.Building != B_NONE || tile.Terrain == T_WATER || tile.Terrain == T_ICE)
                    continue;

                candidates.Add(tile);
            }
        }

        int needed = StarterMinimumPlainsTiles - plainsCount;
        if (needed <= 0 || candidates.Count == 0)
            return;

        candidates.Sort((left, right) =>
        {
            int leftDistance = OffsetHexDist(left.Q, left.R, originQ, originR);
            int rightDistance = OffsetHexDist(right.Q, right.R, originQ, originR);
            if (leftDistance != rightDistance)
                return leftDistance.CompareTo(rightDistance);

            int terrainCompare = StarterTerrainPreference(left.Terrain).CompareTo(StarterTerrainPreference(right.Terrain));
            if (terrainCompare != 0)
                return terrainCompare;

            int rowCompare = left.R.CompareTo(right.R);
            return rowCompare != 0 ? rowCompare : left.Q.CompareTo(right.Q);
        });

        int forestDelta = 0;
        int carbonDelta = 0;

        for (int i = 0; i < candidates.Count && needed > 0; i++)
        {
            TileRow candidate = candidates[i];
            if (candidate.Terrain == T_PLAINS)
                continue;

            carbonDelta += TileCarbonValue(T_PLAINS) - TileCarbonValue(candidate.Terrain);
            if (candidate.Terrain == T_FOREST)
                forestDelta--;

            ctx.Db.Tiles.Id.Update(candidate with
            {
                Terrain = T_PLAINS,
                LastUpdate = tick
            });
            RemoveRecoveryCandidate(ctx, candidate.Id);

            needed--;
        }

        if (forestDelta == 0 && carbonDelta == 0)
            return;

        if (ctx.Db.WorldState.WorldId.Find(DefaultWorldId) is WorldStateRow ws)
        {
            ctx.Db.WorldState.WorldId.Update(ws with
            {
                ForestTotal = Math.Max(0, ws.ForestTotal + forestDelta),
                CarbonTotal = Math.Max(0, ws.CarbonTotal + carbonDelta)
            });
        }
    }

    private static void EnsureOwnedStarterBuildZone(ReducerContext ctx, string wallet)
    {
        long tick = ctx.Db.WorldState.WorldId.Find(DefaultWorldId) is WorldStateRow ws ? ws.Tick : 0L;

        foreach (var tile in ctx.Db.Tiles.Iter())
        {
            if (!string.Equals(tile.Owner, wallet, StringComparison.Ordinal))
                continue;

            if (tile.Building != B_SETTLEMENT)
                continue;

            EnsureStarterBuildZone(ctx, wallet, tile.Q, tile.R, tick);
            return;
        }
    }

    private static int StarterTerrainPreference(int terrain) => terrain switch
    {
        T_DEFORESTED => 0,
        T_FOREST => 1,
        T_DESERT => 2,
        T_BARREN => 3,
        T_MOUNTAIN => 4,
        _ => 5
    };

    private static List<(int q, int r)> CollectOccupiedSettlementOrigins(ReducerContext ctx)
    {
        var settlements = new List<(int q, int r)>();

        foreach (var tile in ctx.Db.Tiles.Iter())
        {
            if (!string.IsNullOrWhiteSpace(tile.Owner) && tile.Building == B_SETTLEMENT)
            {
                settlements.Add((tile.Q, tile.R));
            }
        }

        return settlements;
    }

    private static bool IsSettlementPlacementOnOuterRing(ReducerContext ctx, int q, int r)
    {
        if (!AnySettlementExists(ctx))
            return true;

        bool ringMatch = false;
        foreach (var tile in ctx.Db.Tiles.Iter())
        {
            if (tile.Building != B_SETTLEMENT || string.IsNullOrWhiteSpace(tile.Owner))
                continue;

            int distance = OffsetHexDist(tile.Q, tile.R, q, r);
            if (distance < SettlementRadius)
                return false;

            if (distance == SettlementRadius)
                ringMatch = true;
        }

        return ringMatch;
    }

