    [SpacetimeDB.Reducer]
    public static void ResearchTech(ReducerContext ctx, string wallet, int techIndex)
    {
        if (ctx.Db.Players.Wallet.Find(wallet) is not PlayerRow p) return;
        int[] costs = { 5, 10, 15 };
        if (techIndex < 0 || techIndex >= costs.Length) return;
        if (p.ResearchPoints < costs[techIndex]) { Log.Warn($"ResearchTech: {wallet} cannot afford."); return; }

        p = p with { ResearchPoints = p.ResearchPoints - costs[techIndex] };
        p = techIndex switch
        {
            0 => p with { TechBasicForestry   = 1 },
            1 => p with { TechRenewableEnergy = 1 },
            2 => p with { TechCarbonCapture   = 1 },
            _ => p
        };
        ctx.Db.Players.Wallet.Update(p);
        Log.Info($"Tech {techIndex} researched by {wallet}.");
    }

