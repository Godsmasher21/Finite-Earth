    private static long PackTileId(int q, int r)
        => ((long)(q + 16384) << 20) | (uint)(r + 16384);

    private static void UpsertTile(ReducerContext ctx, TileRow? existing, TileRow tile)
    {
        if (existing == null)
            ctx.Db.Tiles.Insert(tile);
        else
            ctx.Db.Tiles.Id.Update(tile);
    }

    private static void UpdateRecoveryCandidate(ReducerContext ctx, TileRow beforeTile, TileRow afterTile)
    {
        bool beforeTracked = beforeTile.Terrain == T_DEFORESTED;
        bool afterTracked = afterTile.Terrain == T_DEFORESTED;
        if (!beforeTracked && !afterTracked)
            return;

        if (afterTracked)
        {
            UpsertRecoveryCandidate(ctx, afterTile);
        }
        else
        {
            RemoveRecoveryCandidate(ctx, afterTile.Id);
        }
    }

    private static void UpsertRecoveryCandidate(ReducerContext ctx, TileRow tile)
    {
        if (tile.Terrain != T_DEFORESTED)
        {
            RemoveRecoveryCandidate(ctx, tile.Id);
            return;
        }

        var row = new RecoveryQueueRow
        {
            Id = tile.Id,
            Q = tile.Q,
            R = tile.R,
            RecoverAtTick = tile.LastUpdate + RecoveryThresholdTicks
        };

        if (ctx.Db.RecoveryQueue.Id.Find(tile.Id) is RecoveryQueueRow)
            ctx.Db.RecoveryQueue.Id.Update(row);
        else
            ctx.Db.RecoveryQueue.Insert(row);
    }

    private static void RemoveRecoveryCandidate(ReducerContext ctx, long tileId)
    {
        if (ctx.Db.RecoveryQueue.Id.Find(tileId) is RecoveryQueueRow existing)
            DeactivateRecoveryCandidate(ctx, existing);
    }

    private static void ClearRecoveryCandidates(ReducerContext ctx)
    {
        foreach (var candidate in ctx.Db.RecoveryQueue.Iter())
        {
            DeactivateRecoveryCandidate(ctx, candidate);
        }
    }

    private static void DeactivateRecoveryCandidate(ReducerContext ctx, RecoveryQueueRow candidate)
    {
        var inactive = candidate with { RecoverAtTick = long.MaxValue };
        if (ctx.Db.RecoveryQueue.Id.Find(inactive.Id) is RecoveryQueueRow)
            ctx.Db.RecoveryQueue.Id.Update(inactive);
    }

    private static void ApplyResources(ref PlayerRow p, int wc, int fc, int mc, int wr, int fr, int mr)
    {
        p = p with
        {
            Wood     = Math.Max(0, Math.Min(999, p.Wood     - wc + wr)),
            Food     = Math.Max(0, Math.Min(999, p.Food     - fc + fr)),
            Minerals = Math.Max(0, Math.Min(999, p.Minerals - mc + mr))
        };
    }

