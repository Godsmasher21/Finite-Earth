    private static bool TrySeedWorldFromRowsJson(ReducerContext ctx, string json)
    {
        if (string.IsNullOrWhiteSpace(json))
            return false;

        string trimmed = json.Trim();
        int arrayStart = -1;
        int rowsKey = trimmed.IndexOf("\"rows\"", StringComparison.OrdinalIgnoreCase);
        if (rowsKey >= 0)
            arrayStart = trimmed.IndexOf('[', rowsKey);
        else if (trimmed.StartsWith("[\"", StringComparison.Ordinal))
            arrayStart = trimmed.IndexOf('[');

        if (arrayStart < 0)
            return false;

        string[] rows = new string[256];
        int rowCount = 0;

        for (int i = arrayStart + 1; i < trimmed.Length; i++)
        {
            char ch = trimmed[i];
            if (ch == ']')
                break;

            if (ch != '"')
                continue;

            int end = i + 1;
            while (end < trimmed.Length && trimmed[end] != '"')
                end++;

            if (end >= trimmed.Length)
                return false;

            if (rowCount >= rows.Length)
            {
                Log.Warn("SeedWorld: rows array is larger than the supported limit.");
                break;
            }

            rows[rowCount] = trimmed.Substring(i + 1, end - i - 1);
            rowCount++;
            i = end;
        }

        if (rowCount == 0)
            return false;

        SeedRows(ctx, rows, rowCount);
        return true;
    }

    private static void SeedRows(ReducerContext ctx, string[] rows, int rowCount)
    {
        if (rows == null || rowCount <= 0)
        {
            Log.Warn("SeedWorld: no rows supplied.");
            return;
        }

        ClearRecoveryCandidates(ctx);
        int forestCount = 0;
        int carbonSum = 0;
        int entryCount = 0;
        int height = rowCount;

        for (int rowIndex = 0; rowIndex < rowCount; rowIndex++)
        {
            string line = rows[rowIndex] ?? string.Empty;
            int r = height - 1 - rowIndex;

            for (int x = 0; x < line.Length; x++)
            {
                int terrain = TerrainFromSeedChar(line[x]);
                int q = x; // offset coords: column index = q directly
                UpsertSeedTile(ctx, q, r, terrain, B_NONE);
                if (terrain == T_DEFORESTED)
                {
                    UpsertRecoveryCandidate(ctx, new TileRow
                    {
                        Id = PackTileId(q, r),
                        Q = q,
                        R = r,
                        Terrain = terrain,
                        Building = B_NONE,
                        Owner = string.Empty,
                        MiningCount = 0,
                        LastUpdate = 0
                    });
                }

                if (terrain == T_FOREST)
                    forestCount++;

                carbonSum += TileCarbonValue(terrain);
                entryCount++;
            }
        }

        if (ctx.Db.WorldState.WorldId.Find(DefaultWorldId) is WorldStateRow ws)
        {
            ctx.Db.WorldState.WorldId.Update(ws with
            {
                ForestTotal = forestCount,
                InitialForest = forestCount,
                CarbonTotal = carbonSum,
                CarbonCap = Math.Max(1000, carbonSum * 2),
                RecoveryIndexBuilt = true
            });
        }

        Log.Info($"World seeded with {entryCount} entries. Forest={forestCount} Carbon={carbonSum} CarbonCap={Math.Max(1000, carbonSum * 2)}.");
    }

    private static void UpsertSeedTile(ReducerContext ctx, int q, int r, int terrain, int building)
    {
        long id = PackTileId(q, r);
        var row = new TileRow
        {
            Id = id,
            Q = q,
            R = r,
            Terrain = terrain,
            Building = building,
            Owner = string.Empty,
            MiningCount = 0,
            LastUpdate = 0
        };

        if (ctx.Db.Tiles.Id.Find(id) is TileRow)
            ctx.Db.Tiles.Id.Update(row);
        else
            ctx.Db.Tiles.Insert(row);
    }

    private static int TerrainFromSeedChar(char value)
    {
        switch (value)
        {
            case 'f':
            case 'F':
                return T_FOREST;
            case 'p':
            case 'P':
                return T_PLAINS;
            case 'm':
            case 'M':
                return T_MOUNTAIN;
            case 'w':
            case 'W':
                return T_WATER;
            case 'e':
            case 'E':
                return T_DESERT;
            case 'b':
            case 'B':
                return T_BARREN;
            case 'd':
            case 'D':
                return T_DEFORESTED;
            case 'a':
            case 'A':
                return T_FARMLAND;
            case 'i':
            case 'I':
                return T_ICE;
            default:
                return T_PLAINS;
        }
    }

    // Minimal JSON parser for SeedWorld — [{q:N,r:N,terrain:N,building:N},...]
    private static List<(int q, int r, int terrain, int building)> ParseSeedRows(string[] rows)
    {
        var result = new List<(int, int, int, int)>();
        if (rows == null || rows.Length == 0) return result;

        int height = rows.Length;
        for (int row = 0; row < rows.Length; row++)
        {
            string line = rows[row] ?? string.Empty;
            int r = height - 1 - row;

            for (int x = 0; x < line.Length; x++)
            {
                int terrain = char.ToUpperInvariant(line[x]) switch
                {
                    'F' => T_FOREST,
                    'P' => T_PLAINS,
                    'M' => T_MOUNTAIN,
                    'W' => T_WATER,
                    'E' => T_DESERT,
                    'B' => T_BARREN,
                    'D' => T_DEFORESTED,
                    'A' => T_FARMLAND,
                    'I' => T_ICE,
                    _   => T_PLAINS,
                };

                int q = x; // offset coords
                result.Add((q, r, terrain, B_NONE));
            }
        }

        return result;
    }

    private static void SeedWorldEntries(ReducerContext ctx, List<(int q, int r, int terrain, int building)> entries)
    {
        if (entries.Count == 0)
        {
            Log.Warn("SeedWorld: no entries supplied.");
            return;
        }

        ClearRecoveryCandidates(ctx);
        foreach (var (q, r, terrain, building) in entries)
        {
            long id = PackTileId(q, r);
            var row = new TileRow
            {
                Id          = id,
                Q           = q,
                R           = r,
                Terrain     = terrain,
                Building    = building,
                Owner       = string.Empty,
                MiningCount = 0,
                LastUpdate  = 0
            };

            if (ctx.Db.Tiles.Id.Find(id) is TileRow)
                ctx.Db.Tiles.Id.Update(row);
            else
                ctx.Db.Tiles.Insert(row);

            if (terrain == T_DEFORESTED)
                UpsertRecoveryCandidate(ctx, row);
        }

        int forestCount = 0;
        int carbonSum = 0;
        foreach (var tile in ctx.Db.Tiles.Iter())
        {
            if (tile.Terrain == T_FOREST) forestCount++;
            carbonSum += TileCarbonValue(tile.Terrain) + BuildingCarbonMod(tile.Building);
        }

        if (ctx.Db.WorldState.WorldId.Find(DefaultWorldId) is WorldStateRow ws)
        {
            ctx.Db.WorldState.WorldId.Update(ws with
            {
                ForestTotal   = forestCount,
                InitialForest = forestCount,
                CarbonTotal   = carbonSum,
                CarbonCap     = Math.Max(1000, carbonSum * 2),
                RecoveryIndexBuilt = true
            });
        }

        Log.Info($"World seeded with {entries.Count} entries. Forest={forestCount} Carbon={carbonSum} CarbonCap={Math.Max(1000, carbonSum * 2)}.");
    }

    private static List<(int q, int r, int terrain, int building)> ParseTilesSeedJson(string json)
    {
        var result = new List<(int, int, int, int)>();
        if (string.IsNullOrEmpty(json)) return result;

        json = json.Trim().TrimStart('[').TrimEnd(']');
        if (string.IsNullOrEmpty(json)) return result;

        foreach (var entry in json.Split(new[] { "},{" }, StringSplitOptions.RemoveEmptyEntries))
        {
            string e = entry.Trim().TrimStart('{').TrimEnd('}');
            int q = 0, r = 0, terrain = T_PLAINS, building = B_NONE;

            foreach (var kv in e.Split(','))
            {
                var parts = kv.Split(':');
                if (parts.Length != 2 || !int.TryParse(parts[1].Trim(), out int val)) continue;
                switch (parts[0].Trim().Trim('"'))
                {
                    case "q":        q        = val; break;
                    case "r":        r        = val; break;
                    case "terrain":  terrain  = val; break;
                    case "building": building = val; break;
                }
            }
            result.Add((q, r, terrain, building));
        }
        return result;
    }
