    // ─── Action application ───────────────────────────────────────────────────

    private static bool ApplyAction(
        ReducerContext ctx,
        ref PlayerRow p,
        ref WorldStateRow ws,
        int actionType,
        int q, int r,
        long tileId,
        TileRow? maybeTile,
        out string reason)
    {
        reason = string.Empty;
        GetActionCost(actionType, p, out int wc, out int fc, out int mc);
        GetActionReward(actionType, out int wr, out int fr, out int mr);

        if (p.Wood < wc || p.Food < fc || p.Minerals < mc)
        {
            reason = "Not enough resources.";
            return false;
        }

        TileRow tile = maybeTile ?? new TileRow
        {
            Id      = tileId,
            Q       = q,
            R       = r,
            Terrain = T_PLAINS,
            Building = B_NONE,
            Owner   = string.Empty,
            MiningCount = 0,
            LastUpdate  = 0
        };
        TileRow originalTile = tile;

        bool isOwned = tile.Owner == p.Wallet;

        if (actionType == A_CLAIM)
        {
            if (isOwned) { reason = "Tile already owned."; return false; }
            if (tile.Terrain == T_WATER || tile.Terrain == T_ICE) { reason = "Cannot claim water or ice."; return false; }
            if (IsClaimBlockedByNonAggressionPact(ctx, q, r, p.Wallet))
            {
                reason = "Non-aggression pact blocks claims near allied borders.";
                return false;
            }
            if (p.OwnedTiles > 0 && !IsAdjacentToOwned(ctx, q, r, p.Wallet))
            {
                reason = "Claim must be adjacent to owned territory.";
                return false;
            }

            tile = tile with { Owner = p.Wallet, LastUpdate = ws.Tick };
            UpsertTile(ctx, maybeTile, tile);
            ApplyOwnedTileStatsDelta(ref p, originalTile, tile);
            ApplyResources(ref p, wc, fc, mc, wr, fr, mr);
            return true;
        }

        if (!isOwned) { reason = "Tile must be owned."; return false; }

        int prevTerrain  = tile.Terrain;
        int prevBuilding = tile.Building;

        switch (actionType)
        {
            case A_SETTLEMENT:
                if (tile.Building != B_NONE) { reason = "Building exists."; return false; }
                if (tile.Terrain  != T_PLAINS) { reason = "Settlement requires plains."; return false; }
                if (!IsSettlementPlacementOnOuterRing(ctx, q, r))
                {
                    reason = $"Settlement must be placed on the outer ring ({SettlementRadius}) of existing settlement influence.";
                    return false;
                }
                tile = tile with { Building = B_SETTLEMENT };
                break;

            case A_BARRACKS:
                if (tile.Building != B_NONE) { reason = "Building exists."; return false; }
                if (tile.Terrain  != T_PLAINS) { reason = "Barracks requires plains."; return false; }
                tile = tile with { Building = B_BARRACKS };
                break;

            case A_INDUSTRY:
                if (tile.Building != B_NONE) { reason = "Building exists."; return false; }
                if (tile.Terrain != T_BARREN && tile.Terrain != T_PLAINS && tile.Terrain != T_MOUNTAIN)
                { reason = "Industry requires barren/plains/mountain."; return false; }
                tile = tile with { Building = B_INDUSTRY };
                break;

            case A_REMOVE:
                if (tile.Building != B_INDUSTRY)
                {
                    reason = "Only industry can be dismantled.";
                    return false;
                }

                tile = tile with { Building = B_NONE };
                GetBuildingRemovalRefund(prevBuilding, out wr, out fr, out mr);
                break;

            case A_HARVEST:
                if (tile.Building != B_NONE) { reason = "Building blocks harvest."; return false; }
                if (tile.Terrain  != T_FOREST) { reason = "Harvest requires forest."; return false; }
                tile = tile with { Terrain = T_DEFORESTED };
                ws = ws with { ForestTotal = Math.Max(0, ws.ForestTotal - 1) };
                break;

            case A_REFOREST:
                if (tile.Building != B_NONE) { reason = "Building blocks reforest."; return false; }
                if (tile.Terrain != T_PLAINS && tile.Terrain != T_BARREN && tile.Terrain != T_DEFORESTED)
                { reason = "Reforest requires plains/barren/deforested."; return false; }
                tile = tile with { Terrain = T_FOREST };
                ws = ws with { ForestTotal = ws.ForestTotal + 1 };
                break;

            case A_FARM:
                if (tile.Building != B_NONE) { reason = "Building blocks farming."; return false; }
                if (tile.Terrain  != T_PLAINS) { reason = "Farm requires plains."; return false; }
                tile = tile with { Terrain = T_FARMLAND };
                p = p with { AgricultureActions = p.AgricultureActions + 1 };
                break;

            case A_IRRIGATE:
                if (tile.Building != B_NONE) { reason = "Building blocks irrigation."; return false; }
                if (tile.Terrain  != T_DESERT) { reason = "Irrigation requires desert."; return false; }
                if (!HasTerrainWithinRadius(ctx, q, r, T_WATER, WaterRadiusIrrigate))
                { reason = "No water source within range."; return false; }
                tile = tile with { Terrain = T_PLAINS, Building = B_RECOVERY };
                p = p with { EcoActions = p.EcoActions + 1 };
                break;

            case A_MINE:
                if (tile.Building != B_NONE) { reason = "Building blocks mining."; return false; }
                if (tile.Terrain != T_MOUNTAIN && tile.Terrain != T_BARREN)
                { reason = "Mine requires mountain or barren."; return false; }
                int newTerrain = tile.Terrain == T_MOUNTAIN ? T_BARREN : tile.Terrain;
                int extraCarbon = ComputeMiningCarbonDelta(tile.MiningCount);
                tile = tile with { Terrain = newTerrain, MiningCount = tile.MiningCount + 1 };
                ws = ws with { CarbonTotal = ws.CarbonTotal + extraCarbon };
                p = p with { IndustrialActions = p.IndustrialActions + 1 };
                break;

            case A_RESTORE:
                if (tile.Building != B_NONE) { reason = "Building blocks restoration."; return false; }
                if (tile.Terrain  != T_BARREN) { reason = "Restore requires barren."; return false; }
                tile = tile with { Terrain = T_PLAINS, Building = B_RECOVERY };
                p = p with { EcoActions = p.EcoActions + 1 };
                break;

            case A_SPAWN_ARMY:
                if (tile.Building != B_BARRACKS) { reason = "Need barracks."; return false; }
                {
                    // Find a free hex to place the army. Prefer the barracks tile; fall back to
                    // adjacent tiles so multiple armies from the same barracks spread out visually.
                    int spawnQ = q, spawnR = r;
                    bool barracksTaken = false;
                    foreach (var existingArmy in ctx.Db.Armies.Iter())
                    {
                        if (existingArmy.Q == q && existingArmy.R == r) { barracksTaken = true; break; }
                    }
                    if (barracksTaken)
                    {
                        // Flat-top hex neighbours: (q±1,r), (q,r±1), (q+1,r-1), (q-1,r+1)
                        int[,] dirs = { {1,0},{-1,0},{0,1},{0,-1},{1,-1},{-1,1} };
                        bool found = false;
                        for (int d = 0; d < 6 && !found; d++)
                        {
                            int nq = q + dirs[d, 0], nr = r + dirs[d, 1];
                            long nid = ((long)nq << 20) | (uint)nr;
                            if (ctx.Db.Tiles.Id.Find(nid) == null) continue;
                            bool occupied = false;
                            foreach (var a in ctx.Db.Armies.Iter())
                            {
                                if (a.Q == nq && a.R == nr) { occupied = true; break; }
                            }
                            if (!occupied) { spawnQ = nq; spawnR = nr; found = true; }
                        }
                        if (!found) { reason = "No free tile to place army."; return false; }
                    }
                    ctx.Db.Armies.Insert(new ArmyRow
                    {
                        Owner        = p.Wallet,
                        Q            = spawnQ,
                        R            = spawnR,
                        LastMoveTick = ws.Tick
                    });
                }
                break;

            default:
                reason = "Unsupported action.";
                return false;
        }

        // When a barracks is removed, delete every army that is sitting on that tile.
        if (prevBuilding == B_BARRACKS && tile.Building != B_BARRACKS)
        {
            var toDelete = new System.Collections.Generic.List<ulong>();
            foreach (var army in ctx.Db.Armies.Iter())
                if (army.Q == q && army.R == r)
                    toDelete.Add(army.Id);
            foreach (var id in toDelete)
                ctx.Db.Armies.Id.Delete(id);
        }

        // Carbon delta
        int carbonBefore = TileCarbonValue(prevTerrain) + BuildingCarbonMod(prevBuilding);
        int carbonAfter  = TileCarbonValue(tile.Terrain) + BuildingCarbonMod(tile.Building);
        ws = ws with { CarbonTotal = Math.Max(0, ws.CarbonTotal + (carbonAfter - carbonBefore)) };

        tile = tile with { LastUpdate = ws.Tick };
        UpsertTile(ctx, maybeTile, tile);
        UpdateRecoveryCandidate(ctx, originalTile, tile);
        ApplyOwnedTileStatsDelta(ref p, originalTile, tile);
        if (actionType == A_SETTLEMENT)
        {
            OwnedTileStats claimedStats = ClaimSettlementRadius(ctx, p.Wallet, q, r, ws.Tick);
            ApplyOwnedTileStatsDelta(ref p,
                claimedStats.OwnedTiles,
                claimedStats.ForestTiles,
                claimedStats.FarmlandTiles,
                claimedStats.SettlementCount,
                claimedStats.IndustryCount,
                claimedStats.RecoveryProjectCount);
        }
        ApplyResources(ref p, wc, fc, mc, wr, fr, mr);
        return true;
    }

