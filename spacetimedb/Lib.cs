        return ctx.WithTx(txCtx =>
        {
            if (txCtx.Db.CredentialAccounts.UsernameNormalized.Find(NormalizeCredentialUsername(SeedCredentialUsername)) is not CredentialAccountRow)
            {
                string seedUsernameNormalized = NormalizeCredentialUsername(SeedCredentialUsername);
                string seedWallet = BuildCredentialWalletAddress(seedUsernameNormalized);
                string seedSalt = BuildPasswordSalt(seedUsernameNormalized, seedNowMs);
                string seedHash = HashCredentialPassword(SeedCredentialPassword, seedSalt);

                txCtx.Db.CredentialAccounts.Insert(new CredentialAccountRow
                {
                    UsernameNormalized = seedUsernameNormalized,
                    Wallet = seedWallet,
                    Username = SeedCredentialUsername,
                    DisplayName = SeedCredentialUsername,
                    PasswordSalt = seedSalt,
                    PasswordHash = seedHash,
                    CreatedAtMs = seedNowMs,
                    UpdatedAtMs = seedNowMs
                });

                txCtx.Db.PlayerIdentities.Insert(new PlayerIdentityRow
                {
                    Wallet = seedWallet,
                    UsernameNormalized = seedUsernameNormalized,
                    Username = SeedCredentialUsername,
                    DisplayName = SeedCredentialUsername,
                    CreatedAtMs = seedNowMs,
                    UpdatedAtMs = seedNowMs
                });
            }

            string trimmedUsername = string.IsNullOrWhiteSpace(username) ? string.Empty : username.Trim();
            string normalizedUsername = NormalizeCredentialUsername(trimmedUsername);
            if (!IsValidCredentialUsername(trimmedUsername))
            {
                return RejectCredentialAuth("Username must be 3-24 characters and use only letters, numbers, or underscores.");
            }

            if (string.IsNullOrWhiteSpace(password) || password.Length < CredentialPasswordMinLength)
            {
                return RejectCredentialAuth($"Password must be at least {CredentialPasswordMinLength} characters.");
            }

            if (txCtx.Db.CredentialAccounts.UsernameNormalized.Find(normalizedUsername) is CredentialAccountRow)
            {
                return RejectCredentialAuth("Username is already taken.");
            }

            string wallet = BuildCredentialWalletAddress(normalizedUsername);
            string salt = BuildPasswordSalt(normalizedUsername, nowMs);
            string hash = HashCredentialPassword(password, salt);

            txCtx.Db.CredentialAccounts.Insert(new CredentialAccountRow
            {
                UsernameNormalized = normalizedUsername,
                Wallet = wallet,
                Username = trimmedUsername,
                DisplayName = trimmedUsername,
                PasswordSalt = salt,
                PasswordHash = hash,
                CreatedAtMs = nowMs,
                UpdatedAtMs = nowMs
            });

            txCtx.Db.PlayerIdentities.Insert(new PlayerIdentityRow
            {
                Wallet = wallet,
                UsernameNormalized = normalizedUsername,
                Username = trimmedUsername,
                DisplayName = trimmedUsername,
                CreatedAtMs = nowMs,
                UpdatedAtMs = nowMs
            });

            Log.Info($"Created credential account for {trimmedUsername}.");
            return AcceptCredentialAuth(wallet, trimmedUsername, trimmedUsername, true);
        });
    }

    // ─── submit_intent ────────────────────────────────────────────────────────

    [SpacetimeDB.Reducer]
    public static void SubmitIntent(ReducerContext ctx, string intentId, string wallet, long clientSeq, int actionType, int q, int r)
    {
        if (ctx.Db.WorldState.WorldId.Find(DefaultWorldId) is not WorldStateRow ws)
        {
            Log.Error("World state not initialized.");
            return;
        }

        PlayerRow p = LoadPlayerForIntent(ctx, wallet);
        ProcessIntent(ctx, ref p, ref ws, intentId, wallet, clientSeq, actionType, q, r);

        ctx.Db.Players.Wallet.Update(p);
        ctx.Db.WorldState.WorldId.Update(ws);
    }

    [SpacetimeDB.Reducer]
    public static void SubmitIntentBatch(
        ReducerContext ctx,
        string wallet,
        string[] intentIds,
        long[] clientSeqs,
        int[] actionTypes,
        int[] qs,
        int[] rs)
    {
        if (ctx.Db.WorldState.WorldId.Find(DefaultWorldId) is not WorldStateRow ws)
        {
            Log.Error("World state not initialized.");
            return;
        }

        if (string.IsNullOrWhiteSpace(wallet)
            || intentIds == null || clientSeqs == null || actionTypes == null || qs == null || rs == null)
        {
            Log.Warn("SubmitIntentBatch: invalid payload.");
            return;
        }

        int count = intentIds.Length;
        if (count == 0)
        {
            return;
        }

        if (clientSeqs.Length != count || actionTypes.Length != count || qs.Length != count || rs.Length != count)
        {
            Log.Warn("SubmitIntentBatch: array length mismatch.");
            return;
        }

        if (count > MaxBatchIntentCount)
        {
            Log.Warn($"SubmitIntentBatch: trimming {count} intents to max {MaxBatchIntentCount}.");
            count = MaxBatchIntentCount;
        }

        PlayerRow p = LoadPlayerForIntent(ctx, wallet);
        for (int i = 0; i < count; i++)
        {
            ProcessIntent(ctx, ref p, ref ws, intentIds[i], wallet, clientSeqs[i], actionTypes[i], qs[i], rs[i]);
        }

        ctx.Db.Players.Wallet.Update(p);
        ctx.Db.WorldState.WorldId.Update(ws);
    }

    private static void ProcessIntent(
        ReducerContext ctx,
        ref PlayerRow p,
        ref WorldStateRow ws,
        string intentId,
        string wallet,
        long clientSeq,
        int actionType,
        int q,
        int r)
    {
        if (p.LastCycle < ws.Cycle)
        {
            p = p with { ActionsThisCycle = 0, LastCycle = ws.Cycle };
        }

        if (clientSeq <= p.LastClientSeq)
        {
            EmitRejectedActionCommit(ctx, intentId, wallet, actionType, q, r, ws.Tick, "Stale client sequence.");
            Log.Warn($"Action {actionType} rejected for {wallet}: stale clientSeq={clientSeq} last={p.LastClientSeq}");
            return;
        }

        PlayerRow beforePlayer = p;
        WorldStateRow beforeWorld = ws;
        p = p with { LastClientSeq = clientSeq };

        long tileId = PackTileId(q, r);
        TileRow? maybeTile = ctx.Db.Tiles.Id.Find(tileId);
        TileRow beforeTile = SnapshotTile(tileId, q, r, maybeTile);

        bool accepted = ApplyAction(ctx, ref p, ref ws, actionType, q, r, tileId, maybeTile, out string rejectReason);
        if (!accepted)
        {
            EmitRejectedActionCommit(ctx, intentId, wallet, actionType, q, r, ws.Tick, rejectReason);
            Log.Warn($"Action {actionType} rejected for {wallet}: {rejectReason}");
            return;
        }

        p = p with { ActionsThisCycle = p.ActionsThisCycle + 1, ActionsTaken = p.ActionsTaken + 1 };

        int forestDelta = ws.ForestTotal - beforeWorld.ForestTotal;
        int carbonDelta = ws.CarbonTotal - beforeWorld.CarbonTotal;
        int sustainabilityDelta = ComputeSustainabilityDelta(forestDelta, carbonDelta);
        p = p with { SustainabilityScore = p.SustainabilityScore + sustainabilityDelta };

        TileRow afterTile = SnapshotTile(tileId, q, r, ctx.Db.Tiles.Id.Find(tileId));
        EmitAcceptedActionCommit(
            ctx,
            intentId,
            wallet,
            actionType,
            q,
            r,
            ws.Tick,
            beforeTile,
            afterTile,
            beforePlayer,
            p,
            forestDelta,
            carbonDelta,
            sustainabilityDelta);
    }

    // ─── advance_cycle (scheduled every 30 seconds) ───────────────────────────

    [SpacetimeDB.Reducer]
    public static void AdvanceCycle(ReducerContext ctx, CycleClockRow clock)
    {
        string stage = "load_world_state";
        try
        {
            if (ctx.Db.WorldState.WorldId.Find(DefaultWorldId) is not WorldStateRow ws)
                return;

            stage = "advance_tick";
            long nextTick = ws.Tick + 1;
            ws = ws with { Tick = nextTick, Cycle = ws.Cycle + 1, RngState = NextRngState(ws.RngState, nextTick) };

            stage = "load_players";
            var playersByWallet = new Dictionary<string, PlayerRow>(StringComparer.Ordinal);
            var resourceShareWallets = new HashSet<string>(StringComparer.Ordinal);
            int carbonReduction = 0;

            foreach (var player in ctx.Db.Players.Iter())
            {
                PlayerRow normalized = NeedsDerivedStateBackfill(player)
                    ? RebuildPlayerDerivedState(ctx, player)
                    : player;

                if (!normalized.Equals(player))
                    ctx.Db.Players.Wallet.Update(normalized);

                playersByWallet[normalized.Wallet] = normalized;
            }

            stage = "load_resource_pacts";
            foreach (var pact in ctx.Db.Pacts.Iter())
            {
                if (pact.Status != 1 || pact.Type != 1)
                    continue;

                if (!string.IsNullOrWhiteSpace(pact.WalletA))
                    resourceShareWallets.Add(pact.WalletA);

                if (!string.IsNullOrWhiteSpace(pact.WalletB))
                    resourceShareWallets.Add(pact.WalletB);
            }

            stage = "build_recovery_index";
            if (!ws.RecoveryIndexBuilt)
            {
                ClearRecoveryCandidates(ctx);
                foreach (var tile in ctx.Db.Tiles.Iter())
                {
                    if (tile.Terrain == T_DEFORESTED)
                        UpsertRecoveryCandidate(ctx, tile);
                }
                ws = ws with { RecoveryIndexBuilt = true };
            }

            stage = "apply_player_income";
            foreach (var entry in playersByWallet)
            {
                var p = entry.Value;
                int wood = p.TechBasicForestry == 1 ? p.ForestTiles : 0;
                int foodProgress = Math.Max(0, p.PassiveFoodProgressMilli) + (p.FarmlandTiles * FarmFoodMilliPerCycle);
                int mineralProgress = Math.Max(0, p.PassiveMineralProgressMilli) + (p.IndustryCount * IndustryMineralMilliPerCycle);
                int research = p.SettlementCount;
                carbonReduction += p.RecoveryProjectCount * (p.TechCarbonCapture == 1 ? 2 : 1);

                if (resourceShareWallets.Contains(p.Wallet))
                {
                    wood     = (int)(wood * 1.25f);
                    foodProgress = (foodProgress * 125) / 100;
                    mineralProgress = (mineralProgress * 125) / 100;
                }

                int food = foodProgress / ResourceMilliScale;
                int minerals = mineralProgress / ResourceMilliScale;
                int nextFoodProgress = foodProgress % ResourceMilliScale;
                int nextMineralProgress = mineralProgress % ResourceMilliScale;

                int nextFood = p.Food + food;
                if (nextFood >= 999)
                {
                    nextFood = 999;
                    nextFoodProgress = 0;
                }

                int nextMinerals = p.Minerals + minerals;
                if (nextMinerals >= 999)
                {
                    nextMinerals = 999;
                    nextMineralProgress = 0;
                }

                p = p with
                {
                    Wood           = Math.Min(p.Wood + wood, 999),
                    Food           = nextFood,
                    Minerals       = nextMinerals,
                    ResearchPoints = p.ResearchPoints + research,
                    Reputation     = ComputeReputation(p),
                    PassiveFoodProgressMilli = nextFoodProgress,
                    PassiveMineralProgressMilli = nextMineralProgress
                };
                ctx.Db.Players.Wallet.Update(p);
            }

            stage = "apply_carbon_reduction";
            if (carbonReduction > 0)
            {
                ws = ws with { CarbonTotal = Math.Max(0, ws.CarbonTotal - carbonReduction) };
            }

            stage = "expire_trade_offers";
            foreach (var offer in ctx.Db.TradeOffers.Iter())
            {
                if (offer.Status == 0 && offer.ExpiresTick <= ws.Tick)
                {
                    ctx.Db.TradeOffers.Id.Update(offer with { Status = 3 });
                }
            }

            stage = "trigger_climate";
            if (CountActiveClimateEvents(ctx, ws.Tick) < MaxActiveClimateEvents
                && PositiveMod(ws.RngState / 10L, 100L) < ComputeClimateChance(ws))
            {
                TriggerClimateEvent(ctx, ws);
            }

            stage = "recover_tiles";
            foreach (var candidate in ctx.Db.RecoveryQueue.Iter())
            {
                if (candidate.RecoverAtTick > ws.Tick)
                    continue;

                if (ctx.Db.Tiles.Id.Find(candidate.Id) is not TileRow tile || tile.Terrain != T_DEFORESTED)
                {
                    DeactivateRecoveryCandidate(ctx, candidate);
                    continue;
                }

                if (IsAdjacentToTerrain(ctx, tile.Q, tile.R, T_BARREN))
                    continue;

                TileRow updated = tile with { Terrain = T_PLAINS, LastUpdate = ws.Tick };
                ctx.Db.Tiles.Id.Update(updated);
                DeactivateRecoveryCandidate(ctx, candidate);
                ws = ws with { CarbonTotal = Math.Max(0, ws.CarbonTotal + (TileCarbonValue(T_PLAINS) - TileCarbonValue(T_DEFORESTED))) };
            }

            stage = "save_world_state";
            ctx.Db.WorldState.WorldId.Update(ws);
        }
        catch (Exception ex)
        {
            Log.Error($"AdvanceCycle failed at {stage}: {ex}");
        }
    }

    // ─── Trade ────────────────────────────────────────────────────────────────

    [SpacetimeDB.Reducer]
    public static void TradeCreate(ReducerContext ctx, string owner,
        int giveWood, int giveFood, int giveMinerals,
        int wantWood, int wantFood, int wantMinerals,
        long expiresInCycles)
    {
        if (ctx.Db.Players.Wallet.Find(owner) is not PlayerRow p)
            return;

        if (p.Wood < giveWood || p.Food < giveFood || p.Minerals < giveMinerals)
        {
            Log.Warn($"TradeCreate: {owner} cannot afford escrow.");
            return;
        }

        long expiresTick = (ctx.Db.WorldState.WorldId.Find(DefaultWorldId) is WorldStateRow ws ? ws.Tick : 0) + expiresInCycles;

        ctx.Db.Players.Wallet.Update(p with { Wood = p.Wood - giveWood, Food = p.Food - giveFood, Minerals = p.Minerals - giveMinerals });

        ctx.Db.TradeOffers.Insert(new TradeOfferRow
        {
            Id           = 0,
            Owner        = owner,
            GiveWood     = giveWood,
            GiveFood     = giveFood,
            GiveMinerals = giveMinerals,
            WantWood     = wantWood,
            WantFood     = wantFood,
            WantMinerals = wantMinerals,
            Status       = 0,
            ExpiresTick  = expiresTick,
            AcceptedBy   = string.Empty
        });
    }

    [SpacetimeDB.Reducer]
    public static void TradeAccept(ReducerContext ctx, ulong offerId, string accepter)
    {
        if (ctx.Db.TradeOffers.Id.Find(offerId) is not TradeOfferRow offer) return;
        if (offer.Status != 0 || offer.Owner == accepter) return;

        if (ctx.Db.Players.Wallet.Find(accepter) is not PlayerRow acc) return;
        if (acc.Wood < offer.WantWood || acc.Food < offer.WantFood || acc.Minerals < offer.WantMinerals)
        {
            Log.Warn($"TradeAccept: {accepter} cannot afford.");
            return;
        }

        ctx.Db.Players.Wallet.Update(acc with
        {
            Wood     = acc.Wood     - offer.WantWood     + offer.GiveWood,
            Food     = acc.Food     - offer.WantFood     + offer.GiveFood,
            Minerals = acc.Minerals - offer.WantMinerals + offer.GiveMinerals
        });

        if (ctx.Db.Players.Wallet.Find(offer.Owner) is PlayerRow own)
        {
            ctx.Db.Players.Wallet.Update(own with
            {
                Wood     = own.Wood     + offer.WantWood,
                Food     = own.Food     + offer.WantFood,
                Minerals = own.Minerals + offer.WantMinerals
            });
        }

        ctx.Db.TradeOffers.Id.Update(offer with { Status = 1, AcceptedBy = accepter });
        Log.Info($"Trade {offerId} accepted by {accepter}.");
    }

    [SpacetimeDB.Reducer]
    public static void TradeCancel(ReducerContext ctx, ulong offerId, string requester)
    {
        if (ctx.Db.TradeOffers.Id.Find(offerId) is not TradeOfferRow offer) return;
        if (offer.Owner != requester || offer.Status != 0) return;

        if (ctx.Db.Players.Wallet.Find(offer.Owner) is PlayerRow p)
        {
            ctx.Db.Players.Wallet.Update(p with
            {
                Wood     = p.Wood     + offer.GiveWood,
                Food     = p.Food     + offer.GiveFood,
                Minerals = p.Minerals + offer.GiveMinerals
            });
        }

        ctx.Db.TradeOffers.Id.Update(offer with { Status = 2 });
    }

