    private static List<TileRow> FilterStarterCandidates(List<TileRow> candidates, List<(int q, int r)> occupiedSettlements)
    {
        if (candidates == null || candidates.Count == 0)
        {
            return new List<TileRow>();
        }

        if (occupiedSettlements == null || occupiedSettlements.Count == 0)
        {
            return candidates;
        }

        var filtered = new List<TileRow>(candidates.Count);
        foreach (TileRow candidate in candidates)
        {
            if (IsStarterTileSeparated(candidate, occupiedSettlements))
            {
                filtered.Add(candidate);
            }
        }

        return filtered;
    }

    private static bool IsStarterTileSeparated(TileRow candidate, List<(int q, int r)> occupiedSettlements)
    {
        if (occupiedSettlements == null || occupiedSettlements.Count == 0)
            return true;

        for (int i = 0; i < occupiedSettlements.Count; i++)
        {
            (int q, int r) settlement = occupiedSettlements[i];
            if (OffsetHexDist(candidate.Q, candidate.R, settlement.q, settlement.r) < StarterSettlementSeparation)
            {
                return false;
            }
        }

        return true;
    }

    private static bool TrySelectStarterTile(List<TileRow> candidates, string wallet, out TileRow starter)
    {
        starter = default;
        if (candidates == null || candidates.Count == 0)
            return false;

        candidates.Sort((left, right) =>
        {
            int rowCompare = left.R.CompareTo(right.R);
            return rowCompare != 0 ? rowCompare : left.Q.CompareTo(right.Q);
        });

        int startIndex = (int)(StableWalletHash(wallet) % (ulong)candidates.Count);
        starter = candidates[startIndex];
        return true;
    }

    private static OwnedTileStats ClaimSettlementRadius(ReducerContext ctx, string wallet, int originQ, int originR, long tick)
    {
        OwnedTileStats claimed = default;
        for (int r = originR - SettlementRadius; r <= originR + SettlementRadius; r++)
        {
            for (int q = originQ - SettlementRadius; q <= originQ + SettlementRadius; q++)
            {
                if (OffsetHexDist(q, r, originQ, originR) > SettlementRadius)
                    continue;

                long tileId = PackTileId(q, r);
                if (ctx.Db.Tiles.Id.Find(tileId) is not TileRow tile)
                    continue;

                if (!string.IsNullOrWhiteSpace(tile.Owner))
                    continue;

                if (tile.Terrain == T_WATER || tile.Terrain == T_ICE)
                    continue;

                TileRow updated = tile with { Owner = wallet, LastUpdate = tick };
                ctx.Db.Tiles.Id.Update(updated);
                if (string.Equals(updated.Owner, wallet, StringComparison.Ordinal))
                    AccumulateOwnedTileStats(ref claimed, updated);
            }
        }

        return claimed;
    }

